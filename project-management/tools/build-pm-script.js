#!/usr/bin/env node
// Builds the ExmentPM portal's script, ExmentPM/resources/js/script.js, from
// the files in ExmentPM/resources/js/src/. Edit those, then run:
//
//   node project-management/tools/build-pm-script.js           (write script.js)
//   node project-management/tools/build-pm-script.js --check   (CI: fail if out of date)
//
// The files are pieces of ONE function, window.PmPortalBoot: they share its
// variables (root, D, L, CSRF, alive() ...), so they are joined in the order
// of FILES below, between the opening and the closing of that function. Each
// piece holds whole statements only, so `node --check` reads every one of
// them on its own (as a CommonJS file, a `return` at the top is allowed), and
// a mistake shows up in the file it is in. The built file is checked too, in
// strict mode, as the browser runs it.
//
// No Blade inside: the values from the server come from the JSON blocks
// #pmportal-data and #pmportal-lang on the page (index.blade.php).
// PortalDefinition::assetUrl('script') copies script.js to public/exment-pm/.
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

// The order matters: a later file may use what an earlier one declared with
// var at run time (function declarations are hoisted, var values are not).
const FILES = [
    'core.js',             // request queue, page title, form styles, small helpers
    'errors.js',           // error wording
    'attributes.js',       // the custom attributes of the issues (ISS02939): form, detail, list, filters, bulk
    'review-reactions.js', // review request, reactions
    'home.js',             // project head, home, archive
    'list.js',             // issue list, bulk edit, CSV, saved conditions, staying current
    'burndown.js',
    'issue-detail.js',     // issue detail, quick edit, related issues
    'issue-record-links.js', // the records of other tables an issue links to (ISS02939)
    'wiki.js',
    'files.js',            // files, Office view
    'attach-edit.js',      // attachments edited in place, their versions (ISS02938)
    'read-receipts.js',
    'writes.js',
    'typeahead.js',
    'comments.js',         // comment composer and actions
    'issue-move.js',       // move / delete an issue
    'form.js',             // in-portal form, native edit modal, unsaved work, back button, drafts
    'form-fields.js',      // issue browser and the editor's fields
    'ai-autofill.js',
    'form-save.js',        // edit / create forms: fetch, prewarm, save
    'embeds.js',           // lazy embedded widgets (board, gantt)
    'routing.js',          // routing, recently viewed
    'events.js',           // tabs, hovercard, other bindings
    'list-events.js',      // paging, tree view, ticking rows, staying current
    'palette.js',          // Ctrl+K: every action of the screen with its key
    'boot.js',             // shortcuts, boot
];

const HEAD = [
    '// Built from resources/js/src/ by project-management/tools/build-pm-script.js: do not edit this file.',
    '//',
    "// Run from index.blade.php's inline call as well: Exment swaps pages through",
    '// pjax, which does not run a script file the page has already loaded, so a',
    "// project opened from another project's page would otherwise get no script",
    '// at all (empty issue list until F5). The ppBound check makes a second call',
    '// for the same page a no-op.',
    'window.PmPortalBoot = function () {',
    "    'use strict';",
    '',
].join('\n');

const TAIL = [
    '};',
    'window.PmPortalBoot();',
    '',
].join('\n');

const DIR = path.join(__dirname, '..', 'ExmentPM', 'resources', 'js');
const SRC = path.join(DIR, 'src');
const OUT = path.join(DIR, 'script.js');

function read(file) {
    return fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
}

function build() {
    const onDisk = fs.readdirSync(SRC).filter((f) => f.endsWith('.js')).sort();
    const listed = FILES.slice().sort();
    const missing = listed.filter((f) => !onDisk.includes(f));
    const extra = onDisk.filter((f) => !listed.includes(f));
    if (missing.length || extra.length) {
        throw new Error('FILES in build-pm-script.js and resources/js/src/ differ.'
            + (missing.length ? ' Missing: ' + missing.join(', ') + '.' : '')
            + (extra.length ? ' Not listed: ' + extra.join(', ') + '.' : ''));
    }
    const parts = FILES.map((f) => {
        const text = read(path.join(SRC, f));
        if (/\{\{|\{!!/.test(text)) {
            throw new Error('src/' + f + ': Blade syntax ({{ or {!!). Put the value into the page\'s JSON block instead.');
        }
        return text.endsWith('\n') ? text : text + '\n';
    });

    return HEAD + parts.join('') + TAIL;
}

// node --check on every source and on the built text. Returns the failures.
function syntaxCheck(builtText) {
    const failures = [];
    const check = (file, label) => {
        try {
            execFileSync(process.execPath, ['--check', file], { stdio: 'pipe' });
        } catch (e) {
            failures.push(label + '\n' + String(e.stderr || e.message).trim());
        }
    };
    FILES.forEach((f) => check(path.join(SRC, f), 'src/' + f));
    const tmp = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'pmjs-')), 'script.js');
    fs.writeFileSync(tmp, builtText);
    check(tmp, 'script.js (built)');
    fs.rmSync(path.dirname(tmp), { recursive: true, force: true });

    return failures;
}

// The pieces share one function scope, so two pieces declaring the same function
// name is not an error: the later one silently wins (#152 had fmt2 in two files,
// and every "版 :n" kept its ":n"). Every name declared at the top of a piece
// must be declared once.
function duplicateNames() {
    const seen = {};
    const out = [];
    FILES.forEach((f) => {
        const re = /^    (?:function\s+([A-Za-z_$][\w$]*)\s*\(|(?:var|let|const)\s+([A-Za-z_$][\w$]*)\s*=)/gm;
        let m;
        const text = read(path.join(SRC, f));
        while ((m = re.exec(text)) !== null) {
            const name = m[1] || m[2];
            if (seen[name] && seen[name] !== f) {
                out.push(name + ': ' + seen[name] + ' and ' + f);
            } else {
                seen[name] = f;
            }
        }
    });
    return out;
}

function main() {
    const checkOnly = process.argv.includes('--check');
    let text;
    try {
        text = build();
    } catch (e) {
        console.error(e.message);
        process.exit(1);
    }
    const dups = duplicateNames();
    if (dups.length) {
        console.error('The same name is declared in two pieces (the later one wins in script.js):\n  ' + dups.join('\n  '));
        process.exit(1);
    }
    const failures = syntaxCheck(text);
    if (failures.length) {
        console.error('Syntax errors (node --check):\n\n' + failures.join('\n\n'));
        process.exit(1);
    }
    if (checkOnly) {
        const current = fs.existsSync(OUT) ? read(OUT) : null;
        if (current !== text) {
            console.error('resources/js/script.js is not the build of resources/js/src/.'
                + ' Run: node project-management/tools/build-pm-script.js and commit script.js.');
            process.exit(1);
        }
        console.log('script.js is up to date (' + FILES.length + ' files, ' + text.length + ' characters); node --check passed.');
        return;
    }
    fs.writeFileSync(OUT, text);
    console.log('Wrote resources/js/script.js (' + FILES.length + ' files, ' + text.length + ' characters).');
}

main();
